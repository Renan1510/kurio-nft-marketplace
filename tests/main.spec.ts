import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{
 await page.goto('/')
 await page.locator('html[data-kurio-ready="true"]').waitFor({timeout:20000})
 const result=await page.evaluate(async()=>{
  const res=await fetch('/api/__test/reset',{method:'POST'})
  return {status:res.status,body:await res.text()}
 })
 expect(result.status,`MSW não respondeu corretamente ao reset: ${result.body}`).toBe(200)
 await page.reload()
 await page.locator('html[data-kurio-ready="true"]').waitFor({timeout:20000})
})
test('catálogo: pesquisa, filtros, paginação, histórico e acesso direto',async({page})=>{
 await expect(page.getByRole('heading',{name:/seja dono do futuro/i})).toBeVisible()
 await page.getByLabel('Buscar NFTs por nome').fill('Emerald')
 await page.getByRole('button',{name:'Buscar',exact:true}).click()
 await expect(page).toHaveURL(/q=Emerald/)
 await expect(page.getByText('Emerald Ape #042').first()).toBeVisible()
 await page.getByRole('button',{name:/Fotografia/}).click()
 await expect(page).toHaveURL(/category=Fotografia/)
 await page.goBack();await expect(page).not.toHaveURL(/category=Fotografia/)
 await page.goto('/nft/nope');await expect(page.getByText('NFT não encontrado',{exact:true})).toBeVisible()
})
test('autenticação, carrinho e confirmação simulada',async({page})=>{
 await page.goto('/nft/emerald');await page.getByRole('button',{name:/Comprar \/ adicionar/}).click();await expect(page.getByText(/adicionado ao carrinho/i)).toBeVisible()
 await page.getByRole('link',{name:/Ver carrinho/}).click()
 await expect(page.getByRole('region',{name:'Itens do carrinho'}).getByText('Emerald Ape #042')).toBeVisible()
 await page.reload();await expect(page.getByRole('region',{name:'Itens do carrinho'}).getByText('Emerald Ape #042')).toBeVisible()
 await page.getByRole('button',{name:'Conectar e finalizar'}).click()
 await page.getByLabel('E-mail').fill('ana@kurio.demo');await page.getByLabel('Senha').fill('demo12345');await page.getByRole('button',{name:'Entrar',exact:true}).last().click()
 await expect(page).toHaveURL(/checkout/)
 await page.getByLabel('Escolha uma carteira cadastrada *').selectOption({index:1})
 await page.getByRole('button',{name:/Conectar carteira/}).click()
 await page.getByRole('button',{name:'Revisar pedido'}).click()
 await page.getByRole('button',{name:'Confirmar pedido simulado'}).click()
 await expect(page.getByRole('heading',{name:'Pedido confirmado!'})).toBeVisible({timeout:20000})
 await expect(page.getByText(/Referência fictícia:/)).toBeVisible()
})
test('cadastro duplicado tem erro da API',async({page})=>{await page.goto('/register');await page.getByLabel('Nome completo').fill('Teste');await page.getByLabel('E-mail').fill('ana@kurio.demo');await page.getByLabel('Senha (mínimo 8 caracteres)').fill('senha1234');await page.getByLabel('Confirme a senha').fill('senha1234');await page.getByRole('button',{name:'Cadastrar'}).click();await expect(page.getByText(/já está cadastrado/)).toBeVisible()})
